"""Append-only JSONL persistence for eval runs + human feedback.

Longitudinal storage so the adaptive loop's benefit can be *charted over time* rather
than just asserted. JSONL (not a DB) is deliberate — zero infra, trivially tailable,
good enough at demo scale.

# ponytail: flat file + full-read on history. Swap for SQLite/Postgres if runs grow large.
"""
from __future__ import annotations

import json
import time
from pathlib import Path


def _append(path_str: str, record: dict) -> None:
    record = {"ts": time.time(), **record}
    p = Path(path_str)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")


def _read(path_str: str, limit: int) -> list[dict]:
    p = Path(path_str)
    if not p.exists():
        return []
    with p.open(encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]
    return rows[-limit:]


def record_eval_run(path_str: str, run: dict) -> None:
    _append(path_str, run)


def read_eval_runs(path_str: str, limit: int = 100, user_id: str | None = None) -> list[dict]:
    target_user = user_id or "guest"
    rows = _read(path_str, limit * 5)
    # Legacy records lack a mode and may have been generated by the old
    # cosine fallback. Do not display them as verified RAGAS results.
    filtered = [
        r for r in rows
        if r.get("user_id") == target_user and r.get("evaluation_mode") == "ragas"
    ]
    return filtered[-limit:]


def record_feedback(path_str: str, fb: dict) -> None:
    _append(path_str, fb)
